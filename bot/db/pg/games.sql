    series_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL,
    name_ru        TEXT,
    name_source    TEXT NOT NULL DEFAULT 'auto',   -- auto / manual
    anchor_game_id BIGINT UNIQUE REFERENCES games(game_id) ON DELETE SET NULL,
    merged_into    BIGINT REFERENCES series(series_id),  -- an old id keeps resolving
    merged_by      TEXT,             -- operator / auto (125): an auto merge is undone
    -- A series a rule names, not an anchor game (111): "lego", a franchise's
    -- sub-series ("key:star wars jedi", "sub:call of duty|modern warfare").
    -- A game is in several series: the rule's and its franchise's.
    rule_key       TEXT,
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL
);

CREATE TABLE game_series (
    game_id    BIGINT NOT NULL REFERENCES games(game_id) ON DELETE CASCADE,
    series_id  BIGINT NOT NULL REFERENCES series(series_id) ON DELETE CASCADE,
    source     TEXT NOT NULL,              -- auto / advisers / manual
    member     BIGINT NOT NULL DEFAULT 1, -- 0: said not to be in it
    p          DOUBLE PRECISION,
    reason     TEXT,                       -- how the game got there
    decided_by TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY (game_id, series_id)
);

